-- 池塘隔离调度档案：隔离池角色、容量、消毒有效期、调入权限，按池一行。
CREATE TABLE IF NOT EXISTS t_disease_pond_guard (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    pond_role VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    capacity INT,
    disinfected_until DATE,
    transfer_in_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    operator VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_disease_guard_pond UNIQUE (pond_id)
);

-- 疫病观察单：发现异常症状即生成。request_id 强制幂等，重复提交返回同一单。
-- 状态 OBSERVING（观察中）/ ISOLATED（已隔离）/ RELEASED（已解除）。
CREATE TABLE IF NOT EXISTS t_disease_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obs_no VARCHAR(48) NOT NULL,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    observe_date DATE NOT NULL,
    symptoms VARCHAR(500) NOT NULL,
    risk_level VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OBSERVING',
    observer VARCHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_disease_obs_no UNIQUE (obs_no),
    CONSTRAINT uk_disease_obs_request UNIQUE (request_id)
);
CREATE INDEX IF NOT EXISTS idx_disease_obs_batch ON t_disease_observation (batch_id);
CREATE INDEX IF NOT EXISTS idx_disease_obs_pond ON t_disease_observation (pond_id);

-- 隔离调度单：一观察单至多一张。解除隔离必须登记复核兽医与复核意见。
CREATE TABLE IF NOT EXISTS t_disease_isolation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isolation_no VARCHAR(56) NOT NULL,
    observation_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    from_pond_id BIGINT NOT NULL,
    to_pond_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ISOLATED',
    isolated_by VARCHAR(64) NOT NULL,
    isolated_time TIMESTAMP NOT NULL,
    vet_name VARCHAR(64),
    vet_review_remark VARCHAR(500),
    released_time TIMESTAMP,
    request_id VARCHAR(64) NOT NULL,
    release_request_id VARCHAR(64),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_disease_isolation_no UNIQUE (isolation_no),
    CONSTRAINT uk_disease_isolation_obs UNIQUE (observation_id),
    CONSTRAINT uk_disease_isolation_request UNIQUE (request_id)
);
CREATE INDEX IF NOT EXISTS idx_disease_isolation_batch ON t_disease_isolation (batch_id, status);
CREATE INDEX IF NOT EXISTS idx_disease_isolation_pond ON t_disease_isolation (to_pond_id, status);

-- 原池与隔离池之间的数量变化：逐笔记录，只追加。调入调出各一笔，操作者随行。
CREATE TABLE IF NOT EXISTS t_disease_stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isolation_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    move_type VARCHAR(16) NOT NULL,
    from_pond_id BIGINT NOT NULL,
    to_pond_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    operator VARCHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_disease_movement_request UNIQUE (request_id)
);
CREATE INDEX IF NOT EXISTS idx_disease_movement_batch ON t_disease_stock_movement (batch_id);
CREATE INDEX IF NOT EXISTS idx_disease_movement_isolation ON t_disease_stock_movement (isolation_id);

-- 定时复查任务：调度系统按观察单按日生成，task_no 唯一保证重启/重跑不多写。
-- operator 固定为调度系统标识，source_observer 保留原观察人，操作者链条不断。
CREATE TABLE IF NOT EXISTS t_disease_followup_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(64) NOT NULL,
    observation_id BIGINT NOT NULL,
    task_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    operator VARCHAR(64) NOT NULL,
    source_observer VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_disease_followup_no UNIQUE (task_no)
);
CREATE INDEX IF NOT EXISTS idx_disease_followup_obs ON t_disease_followup_task (observation_id, task_date);

-- 疫病模块变更证据：所有修改留痕（含调度失败及冲突原因），只追加；operator 列保证不丢操作者。
CREATE TABLE IF NOT EXISTS t_disease_change_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    request_id VARCHAR(64),
    operator VARCHAR(64) NOT NULL,
    before_json CLOB,
    after_json CLOB,
    detail VARCHAR(1000),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_disease_evidence_entity ON t_disease_change_evidence (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_disease_evidence_request ON t_disease_change_evidence (request_id);

