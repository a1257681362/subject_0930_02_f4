-- ============================================================
-- aqua-3 饲料批号管理与配方投喂
-- 饲料批号三量账（入库/锁定占用/已消耗），过期或可用库存不足拦截；
-- 配方按苗种、日龄、水温选择，版本化发布，投喂单建立即冻结版本快照；
-- 投喂单锁定后才允许执行；临时减量登记原因与审批人；
-- 日汇总试喂与正式投喂分列；所有修改保留证据。
-- ============================================================

-- 饲料批号：一批饲料一行，三量账 quantity_in / quantity_locked / quantity_consumed。
-- 可用量 = 入库 - 锁定占用 - 已消耗。批号不可删除，只能消耗推进；过期批号禁止再被占用。
CREATE TABLE IF NOT EXISTS t_feed_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(40) NOT NULL,
    feed_name VARCHAR(64) NOT NULL,
    supplier VARCHAR(128),
    quantity_in DECIMAL(10,2) NOT NULL,
    quantity_locked DECIMAL(10,2) NOT NULL DEFAULT 0,
    quantity_consumed DECIMAL(10,2) NOT NULL DEFAULT 0,
    production_date DATE,
    expiry_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'IN_STOCK',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_feed_batch_no UNIQUE (batch_no)
);
CREATE INDEX IF NOT EXISTS idx_feed_batch_name ON t_feed_batch (feed_name);

-- 批号占用明细：投喂单锁定时为每个投喂明细对具体批号加锁，执行后转消耗，解锁则释放。
CREATE TABLE IF NOT EXISTS t_feed_batch_lock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_batch_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    quantity_kg DECIMAL(10,2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'LOCKED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_feed_batch_lock_batch ON t_feed_batch_lock (feed_batch_id);
CREATE INDEX IF NOT EXISTS idx_feed_batch_lock_item ON t_feed_batch_lock (order_item_id);

-- 投喂配方版本：同一苗种代码同一时刻仅一个 ACTIVE 版本（发布时旧版本置 SUPERSEDED）。
CREATE TABLE IF NOT EXISTS t_feed_formula_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    species VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_feed_formula_version_no UNIQUE (version_no)
);
CREATE INDEX IF NOT EXISTS idx_feed_formula_species ON t_feed_formula_version (species, status);

-- 配方规则行：按 苗种 + 日龄区间 + 水温区间 选择饲料与计划投喂量。
-- 随版本快照存在，发布后不改；区间闭区间匹配，命中多行时取区间最窄（最具体）的一行。
CREATE TABLE IF NOT EXISTS t_feed_formula_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    species VARCHAR(64) NOT NULL,
    day_age_from INT NOT NULL,
    day_age_to INT NOT NULL,
    water_temp_from DECIMAL(5,2) NOT NULL,
    water_temp_to DECIMAL(5,2) NOT NULL,
    feed_name VARCHAR(64) NOT NULL,
    planned_qty_kg DECIMAL(8,2) NOT NULL,
    sort_no INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_feed_formula_rule_version ON t_feed_formula_rule (version_id);

-- 投喂单：按池按批按日。建立即冻结当时的配方版本，状态 DRAFT/LOCKED/EXECUTED。
